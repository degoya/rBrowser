import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

// RB-080-83: the panels on Nuxt UI. Each is built by Vite from its web/src (panel-ui's
// vite.panel.ts) into panel/dist - one classic script, one stylesheet and the licences of what
// they bundle -, loads only those, carries no copy of the old kit, and names its third-party code
// in its NOTICE. Their freshness is each panel's own test (src/bundle.test.ts).

const PLUGINS = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (...path: string[]): string => readFileSync(join(PLUGINS, ...path), 'utf8');

/** The panels on Nuxt UI (RB-080-83 … RB-080-86). */
const NUXT_PANELS = ['lighthouse', 'fonts', 'image-overlay', 'rulers-guides', 'overlays', 'simulators', 'form-autofill', 'screenshot-editor', 'color-picker', 'coverage', 'console', 'error-report', 'network-panel', 'snippets', 'storage-panel', 'seo', 'pwa-check', 'outline'];

describe.each(NUXT_PANELS)('the %s panel on Nuxt UI', (plugin) => {
  it('loads its built stylesheet and script, nothing else', () => {
    const page = read(plugin, 'panel', 'index.html');
    expect(page).toContain('<link rel="stylesheet" href="dist/panel.css" />');
    expect(page).toContain('<script src="dist/panel.js"></script>');
    expect(page.indexOf('<div id="app"></div>')).toBeLessThan(page.indexOf('<script src="dist/panel.js">'));
    expect(page).not.toMatch(/kit\.css|icons\.js|type="module"|https?:/);
    for (const old of ['kit.css', 'icons.js', 'panel.js', 'panel.css']) {
      expect(existsSync(join(PLUGINS, plugin, 'panel', old)), `plugins/${plugin}/panel/${old}`).toBe(false);
    }
  });

  it('mounts through panel-ui', () => {
    expect(read(plugin, 'web', 'src', 'panel', 'main.ts')).toContain("from '../../../../web-common/panel-ui/src/mount'");
    expect(read(plugin, 'web', 'vite.config.ts')).toContain('panelConfig(');
  });

  it('ships the licences of what it bundles and names them in its NOTICE', () => {
    const licences = read(plugin, 'panel', 'dist', 'THIRD-PARTY-LICENSES.txt');
    for (const name of ['@nuxt/ui ', 'vue ', 'reka-ui ', 'tailwindcss ', '@iconify-json/lucide ']) expect(licences).toContain(`\n${name}`);
    expect(licences).toContain('Lucide - ISC License');
    expect(read(plugin, 'panel', 'dist', 'panel.js')).toMatch(/^\/\* Generated by plugins\/[a-z-]+\/web/);
    const notice = read(plugin, 'NOTICE');
    expect(notice).toContain('panel/dist/THIRD-PARTY-LICENSES.txt');
    expect(notice).toContain('Lucide');
  });
});
