// The Vite build of a Nuxt UI panel (RB-080-83). Each panel is built on its own - Vue, the Nuxt
// UI components it uses and the Tailwind classes it names, nothing else - into one classic
// script and one stylesheet, because the frame is sandboxed with an opaque origin (no
// `type="module"`) and has no network: `panel/dist/panel.js` and `panel/dist/panel.css`, plus
// `panel/dist/THIRD-PARTY-LICENSES.txt`, the licence of every package bundled in. Committed like
// the other built panels (scripts/build-plugins.sh packs without npm); a test of the panel builds
// it again and compares (`builtFiles`). The theme is the shell's: primary teal, neutral slate;
// the colour mode is `ui.theme` (src/theme.ts), never `localStorage`.

import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import vue from '@vitejs/plugin-vue';
import ui from '@nuxt/ui/vite';
import type { InlineConfig, Plugin } from 'vite';

const PLUGINS = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

export interface PanelBuild {
  /** The panel's web package (`plugins/<id>/web`). */
  root: string;
  /** Its entry below `root`. */
  entry?: string;
  /** The folder of the built files below `root`. */
  outDir?: string;
  /** The plugin's id, for the header of the built files. */
  id: string;
  /** The SPDX licence of the panel's own code in the header (RB-080-87): a plugin of another
   * author names its own; rBrowser's first-party plugins `GPL-3.0-or-later`, the default. */
  license?: string;
  /** Where the header says the files come from; `plugins/<id>/web` by default. */
  source?: string;
}

/** The licence texts of packages that ship none (Lucide's icon data: ISC, and MIT for the icons
 * derived from Feather). */
const OWN_TEXTS: Record<string, string> = {
  '@iconify-json/lucide': join(dirname(fileURLToPath(import.meta.url)), 'licences', 'lucide.txt'),
};

const LICENCE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md', 'LICENCE', 'LICENSE-MIT'];

/** The package folder a module of `node_modules` belongs to, or undefined. */
export function packageOf(id: string): string | undefined {
  const marker = `${sep}node_modules${sep}`;
  const at = id.lastIndexOf(marker);
  if (at < 0) return undefined;
  const rest = id.slice(at + marker.length).split(sep);
  const name = rest[0]?.startsWith('@') ? rest.slice(0, 2).join(sep) : rest[0];
  return name ? id.slice(0, at + marker.length) + name : undefined;
}

/** The licence text of every package `ids` come from, sorted by name; Tailwind's always. */
export function licences(ids: Iterable<string>): string {
  const folders = new Set<string>();
  for (const id of ids) {
    const folder = packageOf(id.replace(/^\0/, '').split('?')[0] ?? '');
    if (folder && existsSync(join(folder, 'package.json'))) folders.add(folder);
  }
  // The compiled styles and the bundled icons come from no module of the chunk.
  folders.add(join(PLUGINS, 'node_modules', 'tailwindcss'));
  folders.add(join(PLUGINS, 'node_modules', '@iconify-json', 'lucide'));
  const entries = [...folders].map((folder) => {
    const meta = JSON.parse(readFileSync(join(folder, 'package.json'), 'utf8')) as { name: string; version: string; license?: string };
    const file = LICENCE_FILES.map((name) => join(folder, name)).find((path) => existsSync(path)) ?? OWN_TEXTS[meta.name];
    const text = file ? readFileSync(file, 'utf8').trim() : `Licence: ${meta.license ?? 'see the package'}`;
    return { key: `${meta.name}@${meta.version}`, text: `${meta.name} ${meta.version} (${meta.license ?? 'unknown'})\n\n${text}` };
  });
  // One entry per name and version (a package may sit in two folders).
  const unique = new Map(entries.map((entry) => [entry.key, entry.text]));
  return [...unique].sort(([a], [b]) => a.localeCompare(b)).map(([, text]) => text).join(`\n\n${'-'.repeat(72)}\n\n`) + '\n';
}

/** Puts the header on the built files and emits `THIRD-PARTY-LICENSES.txt` for the packages the
 * bundle holds. */
function licencePlugin(options: PanelBuild): Plugin {
  const { id } = options;
  const banner = `/* Generated by ${options.source ?? `plugins/${id}/web`} (npm run build) - do not edit. SPDX-License-Identifier: ${options.license ?? 'GPL-3.0-or-later'}. Third-party code: see THIRD-PARTY-LICENSES.txt beside this file. */\n`;
  return {
    name: 'rbrowser:panel-licences',
    enforce: 'post',
    generateBundle(_, bundle) {
      const ids = new Set<string>();
      for (const output of Object.values(bundle)) {
        if (output.type === 'chunk') {
          for (const module of output.moduleIds) ids.add(module);
          output.code = banner + output.code;
        } else if (output.fileName.endsWith('.css') && typeof output.source === 'string') {
          output.source = banner + output.source;
        }
      }
      const head = `Third-party code in the ${id} plugin's panel (panel/dist/panel.js, panel/dist/panel.css), RB-080-83.\nEach package below is bundled unchanged, under its licence.\n\n`;
      this.emitFile({ type: 'asset', fileName: 'THIRD-PARTY-LICENSES.txt', source: head + licences(ids) });
    },
  };
}

/** The icons panel-ui's own components name, which the scan of a panel's folder does not see. */
const PANEL_UI_ICONS = ['lucide:settings'];

/** The Vite configuration of a panel. */
export function panelConfig(options: PanelBuild): InlineConfig {
  return {
    root: options.root,
    logLevel: 'warn',
    base: './',
    plugins: [
      vue(),
      ui({
        router: false,
        colorMode: false,
        dts: false,
        ui: { colors: { primary: 'teal', neutral: 'slate' } },
        // The scan reads the panel's own folder; the icons panel-ui's components name themselves
        // are listed (SettingLink's, RB-094-21).
        icon: { clientBundle: { scan: true, icons: PANEL_UI_ICONS } },
      }),
      licencePlugin(options),
    ],
    define: { 'process.env.NODE_ENV': '"production"', 'import.meta.dev': 'false' },
    build: {
      outDir: options.outDir ?? '../panel/dist',
      emptyOutDir: true,
      minify: true,
      cssCodeSplit: false,
      modulePreload: false,
      reportCompressedSize: false,
      lib: {
        entry: options.entry ?? 'src/panel/main.ts',
        formats: ['iife'],
        name: 'RbPanel',
        fileName: () => 'panel.js',
        cssFileName: 'panel',
      },
    },
  };
}

/** The files the build of `options` writes, by name: `vite build` of its package in a process of
 * its own (a test runner's NODE_ENV=test would make the Vue plugin compile for development),
 * into a temporary folder. */
export function builtFiles(options: PanelBuild): Map<string, string> {
  const out = mkdtempSync(join(tmpdir(), `rb-panel-${options.id}-`));
  try {
    const env = { ...process.env };
    delete env.NODE_ENV;
    delete env.VITEST;
    const vite = join(PLUGINS, 'node_modules', 'vite', 'bin', 'vite.js');
    const run = spawnSync(process.execPath, [vite, 'build', '--outDir', out, '--emptyOutDir', '--logLevel', 'error'], { cwd: options.root, env, encoding: 'utf8' });
    if (run.status !== 0) throw new Error(`vite build of ${options.id} failed: ${run.stderr}`);
    return new Map(readdirSync(out).map((name) => [name, readFileSync(join(out, name), 'utf8')]));
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}

/** The size budget of a panel's built files, in bytes: Vue, the Nuxt UI components a panel uses
 * and the compiled styles, with a margin (RB-080-83, the spike's figures; Nuxt UI 4.13 added about
 * 5 KiB to every panel, the largest - form autofill - then stood at 644 KiB). */
export const BUDGET: Record<string, number> = { 'panel.js': 672 * 1024, 'panel.css': 256 * 1024 };

/** The built files of `options` that differ from those in its `outDir` (missing, stale, or one
 * there that the build no longer writes), and those over the budget. */
export function checkBuilt(options: PanelBuild): { stale: string[]; over: string[] } {
  const files = builtFiles(options);
  const dir = resolve(options.root, options.outDir ?? '../panel/dist');
  const stale = [...files].filter(([name, text]) => !existsSync(join(dir, name)) || readFileSync(join(dir, name), 'utf8') !== text).map(([name]) => name);
  const extra = existsSync(dir) ? readdirSync(dir).filter((name) => !files.has(name)) : [];
  const over = [...files].filter(([name, text]) => Buffer.byteLength(text) > (BUDGET[name] ?? Number.POSITIVE_INFINITY)).map(([name, text]) => `${name}: ${Buffer.byteLength(text)} bytes`);
  return { stale: [...stale, ...extra], over };
}
