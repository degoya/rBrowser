// Builds the width sweep's detector, one minified IIFE: src/detect-entry.ts into ../src/detect.js
// (the global `WidthSweepDetect`), which the component embeds and evaluates at every width. It is
// committed - scripts/build-plugins.sh builds without npm - and src/bundle.test.ts fails when it
// is stale. Minified because the 500-line rule exempts only dist/; the sources are web/src. Fails
// above a size budget of 32 kB: the script goes to the view with every width.

import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const BUDGET = 32 * 1024;

export const BUNDLES = [{ entry: 'src/detect-entry.ts', out: '../src/detect.js', globalName: 'WidthSweepDetect' }];

const HEADER =
  '// Generated by plugins/width-sweep/web (npm run build) from web/src - do not edit.\n' +
  '// SPDX-License-Identifier: GPL-3.0-or-later\n';

/** The text of one bundle, as `npm run build` writes it. */
export async function bundle({ entry, globalName }) {
  const result = await build({
    absWorkingDir: resolve(here, '..'),
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'iife',
    globalName,
    minify: true,
    charset: 'utf8',
    target: 'chrome120',
    legalComments: 'none',
    logLevel: 'warning',
  });
  return HEADER + result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  let failed = false;
  for (const spec of BUNDLES) {
    const text = await bundle(spec);
    const out = resolve(here, '..', spec.out);
    writeFileSync(out, text);
    const size = Buffer.byteLength(text);
    if (size > BUDGET) {
      console.error(`${spec.out} is ${size} bytes, over the budget of ${BUDGET}`);
      failed = true;
    } else {
      console.log(`${spec.out}: ${size} bytes (budget ${BUDGET})`);
    }
  }
  if (failed) process.exit(1);
}
