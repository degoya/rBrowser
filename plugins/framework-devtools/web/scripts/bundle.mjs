// Builds the plugin's scripts: src/main-bridge.ts into ../page/bridge.js (the page script, one
// minified IIFE that defines no global), src/react-panel.tsx into ../panel/dist/react.js (the React
// DevTools frontend with react, react-dom and react-is) and src/vue-panel.ts into
// ../panel/dist/vue.js (the Vue component tree with birpc and the kit's parser; panel/dist/
// because the 500-line rule exempts only dist/ and the minified frontend keeps the newlines of
// its strings). Beside them ../panel/dist/THIRD-PARTY-LICENSES.txt, the licence text of every
// package the bundles hold (RB-099-12), which the plugin package carries. Committed -
// scripts/build-plugins.sh packs and builds without npm, and the package carries page/ and
// panel/ - and src/bundle.test.ts fails when one is stale. Minified because the 500-line rule
// exempts only dist/; the sources are web/src. Each bundle has a size budget: the page script
// the limit of a page script (64 kB), the panels their third-party code plus a margin.

import { build } from 'esbuild';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

export const BUNDLES = [
  { entry: 'src/main-bridge.ts', out: '../page/bridge.js', budget: 64 * 1024 },
  { entry: 'src/react-panel.tsx', out: '../panel/dist/react.js', budget: 1536 * 1024 },
  { entry: 'src/vue-panel.ts', out: '../panel/dist/vue.js', budget: 256 * 1024 },
];

const HEADER =
  '// Generated by plugins/framework-devtools/web (npm run build) from web/src - do not edit.\n' +
  '// SPDX-License-Identifier: GPL-3.0-or-later\n' +
  '// Third-party code (MIT): see panel/dist/THIRD-PARTY-LICENSES.txt.\n';

const LICENCES = '../panel/dist/THIRD-PARTY-LICENSES.txt';
// As plugins/web-common/panel-ui/vite.panel.ts reads them.
const LICENCE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md', 'LICENCE', 'LICENSE-MIT'];

/** esbuild's result for one bundle. */
function run({ entry }, metafile = false) {
  return build({
    metafile,
    absWorkingDir: resolve(here, '..'),
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'iife',
    minify: true,
    charset: 'utf8',
    target: 'chrome120',
    legalComments: 'none',
    logLevel: 'warning',
    jsx: 'automatic',
    // The React DevTools frontend reads these as a bundler's constants.
    define: { 'process.env.NODE_ENV': '"production"', 'process.env.NODE_DEBUG': 'undefined' },
  });
}

/** The text of one bundle, as `npm run build` writes it. */
export async function bundle(spec) {
  const result = await run(spec);
  return HEADER + result.outputFiles[0].text;
}

/** The package folder of a module below `node_modules`, or undefined. */
function packageOf(path) {
  const marker = `${sep}node_modules${sep}`;
  const at = path.lastIndexOf(marker);
  if (at < 0) return undefined;
  const rest = path.slice(at + marker.length).split(sep);
  const name = rest[0]?.startsWith('@') ? rest.slice(0, 2).join(sep) : rest[0];
  return name ? path.slice(0, at + marker.length) + name : undefined;
}

/** THIRD-PARTY-LICENSES.txt: name, version, licence and licence text of every package the
 * bundles hold, sorted by name. */
export async function thirdPartyLicences() {
  const folders = new Set();
  for (const spec of BUNDLES) {
    const { metafile } = await run(spec, true);
    for (const input of Object.keys(metafile.inputs)) {
      const folder = packageOf(resolve(here, '..', input));
      if (folder && existsSync(join(folder, 'package.json'))) folders.add(folder);
    }
  }
  const entries = new Map();
  for (const folder of folders) {
    const meta = JSON.parse(readFileSync(join(folder, 'package.json'), 'utf8'));
    const file = LICENCE_FILES.map((name) => join(folder, name)).find((path) => existsSync(path));
    const text = file ? readFileSync(file, 'utf8').trim() : `Licence: ${meta.license ?? 'see the package'}`;
    entries.set(`${meta.name}@${meta.version}`, `${meta.name} ${meta.version} (${meta.license ?? 'unknown'})\n\n${text}`);
  }
  const head =
    "Third-party code in the framework-devtools plugin (panel/dist/react.js, panel/dist/vue.js,\n" +
    'page/bridge.js), RB-080-24. Each package below is bundled unchanged, under its licence.\n\n';
  const body = [...entries].sort(([a], [b]) => a.localeCompare(b)).map(([, text]) => text);
  return head + body.join(`\n\n${'-'.repeat(72)}\n\n`) + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  let failed = false;
  for (const spec of BUNDLES) {
    const text = await bundle(spec);
    const out = resolve(here, '..', spec.out);
    writeFileSync(out, text);
    const size = Buffer.byteLength(text);
    if (size > spec.budget) {
      console.error(`${spec.out} is ${size} bytes, over the budget of ${spec.budget}`);
      failed = true;
    } else {
      console.log(`${spec.out}: ${size} bytes (budget ${spec.budget})`);
    }
  }
  writeFileSync(resolve(here, '..', LICENCES), await thirdPartyLicences());
  console.log(`${LICENCES}: written`);
  if (failed) process.exit(1);
}
