// Builds the two scripts of the Peek plugin, each one minified IIFE: src/main.ts, the page
// script, into ../page/peek.js, and src/collect-entry.ts, the collector of `peek_inspect` (the
// global `PeekCollect`), into ../src/collect.js, which the component embeds. Both are committed -
// scripts/build-plugins.sh packs and builds without npm, and the package carries page/ - and
// src/bundle.test.ts fails when they are stale. Minified because the 500-line rule exempts only
// dist/; the sources are web/src. Fails above the size budget of a page script (64 kB).

import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const BUDGET = 64 * 1024;

export const BUNDLES = [
  { entry: 'src/main.ts', out: '../page/peek.js' },
  { entry: 'src/collect-entry.ts', out: '../src/collect.js', globalName: 'PeekCollect' },
];

const HEADER =
  '// Generated by plugins/peek/web (npm run build) from web/src - do not edit.\n' +
  '// SPDX-License-Identifier: GPL-3.0-or-later\n';

/** The text of one bundle, as `npm run build` writes it. */
export async function bundle({ entry, globalName }) {
  const result = await build({
    absWorkingDir: resolve(here, '..'),
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'iife',
    globalName,
    minify: true,
    charset: 'utf8',
    target: 'chrome120',
    legalComments: 'none',
    logLevel: 'warning',
  });
  return HEADER + result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  let failed = false;
  for (const spec of BUNDLES) {
    const text = await bundle(spec);
    const out = resolve(here, '..', spec.out);
    writeFileSync(out, text);
    const size = Buffer.byteLength(text);
    if (size > BUDGET) {
      console.error(`${spec.out} is ${size} bytes, over the budget of ${BUDGET}`);
      failed = true;
    } else {
      console.log(`${spec.out}: ${size} bytes (budget ${BUDGET})`);
    }
  }
  if (failed) process.exit(1);
}
