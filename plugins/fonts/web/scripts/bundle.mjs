// Builds the page part of the Fonts plugin, one minified IIFE: src/collect-entry.ts, which the
// component evaluates in every view (the global `FontsPage`), into ../src/page.js, which the
// component embeds. Committed - scripts/build-plugins.sh packs and builds without npm - and
// src/bundle.test.ts fails when it is stale. Minified because the 500-line rule exempts only
// generated one-liners; the sources are web/src. Fails above the size budget (64 kB). The panel
// is built by Vite (vite.config.ts, RB-080-83).

import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const BUDGET = 64 * 1024;

export const BUNDLES = [
  { entry: 'src/collect-entry.ts', out: '../src/page.js', globalName: 'FontsPage' },
];

const HEADER =
  '// Generated by plugins/fonts/web (npm run build) from web/src - do not edit.\n' +
  '// SPDX-License-Identifier: GPL-3.0-or-later\n';

/** The text of one bundle, as `npm run build` writes it. */
export async function bundle({ entry, globalName }) {
  const result = await build({
    absWorkingDir: resolve(here, '..'),
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'iife',
    globalName,
    minify: true,
    charset: 'utf8',
    target: 'chrome120',
    legalComments: 'inline',
    logLevel: 'warning',
  });
  return HEADER + result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  let failed = false;
  for (const spec of BUNDLES) {
    const text = await bundle(spec);
    const out = resolve(here, '..', spec.out);
    writeFileSync(out, text);
    const size = Buffer.byteLength(text);
    if (size > BUDGET) {
      console.error(`${spec.out} is ${size} bytes, over the budget of ${BUDGET}`);
      failed = true;
    } else {
      console.log(`${spec.out}: ${size} bytes (budget ${BUDGET})`);
    }
  }
  if (failed) process.exit(1);
}
