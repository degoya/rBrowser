// Robust selectors (RB-020-01): an element of one view found again in another view of another
// width. In this order: `data-testid`, ARIA role + accessible name, a stable unique id, tag +
// text (not for containers of controls), CSS path. The
// CSS path prefers stable ids and classes and avoids generated ones (`css-1x2y3z`, CSS modules,
// styled-components); it is also the fallback of every other kind. Open shadow roots are
// walked: the hosts above an element come with its target. A later role or text match also
// carries its index among the visible matches (`visibleNth`, RB-090-81), which a recording's
// export uses: the breakpoints differ in what they hide, not in what a person picked. Texts and
// names are read as the page had them before a pseudo-localisation (RB-092-02,
// `locale/originals.ts`), so a pseudo-localised view keeps the sync.

import { originalText } from './locale/originals';
import type { ElementSelector, ElementTarget } from './protocol';
import { MAX_NAME, nameOf, normalize, roleOf } from './role';
import { isVisible } from './visible';

/** Texts longer than this are no selector. */
export const MAX_TEXT = 80;
/** An element holding one of these is a container, not a text. */
const CONTROLS = 'a[href],button,input,select,textarea';

/** Where a selector is evaluated: a document or an open shadow root. */
export type Root = Document | ShadowRoot;

/** What a click inside is meant for: the nearest interactive ancestor. */
const ACTIONABLE = [
  'a[href]', 'button', 'input', 'select', 'textarea', 'label', 'summary', 'option',
  '[contenteditable=""]', '[contenteditable="true"]',
  ...['button', 'link', 'checkbox', 'radio', 'switch', 'tab', 'menuitem', 'option'].map(
    (role) => `[role="${role}"]`,
  ),
].join(',');

/** The elements that can have a role, by role (plus `[role=...]`). */
const ROLE_TAGS: Record<string, string> = {
  button: 'button,input,summary',
  link: 'a,area',
  checkbox: 'input',
  radio: 'input',
  slider: 'input',
  spinbutton: 'input',
  searchbox: 'input',
  textbox: 'input,textarea',
  combobox: 'select',
  listbox: 'select',
  option: 'option',
  heading: 'h1,h2,h3,h4,h5,h6',
  img: 'img',
  navigation: 'nav',
};

/** CSS-in-JS and scoped styles: css-1x2y3z, sc-bdfBwQ, jsx-123456, svelte-1abc2d. */
const GENERATED_PREFIX = /^(css|sc|jsx|jss|emotion|styled|svelte|astro)-/i;
/** CSS modules: Button_root__a1B2c. */
const CSS_MODULE = /__[A-Za-z0-9_-]{5,}$/;
/** A styled-components hash: kGfCyH. */
const MIXED_CASE = /^[a-zA-Z][a-z]*[A-Z][a-z]*[A-Z][a-zA-Z]*$/;
/** Classes that come and go with the element's state. */
const STATE_CLASS =
  /^((is|has)-.*|active|current|selected|open|opened|closed|expanded|collapsed|checked|disabled|focus|focused|hover|hovered|visible|hidden|show|shown|in|fade)$/;
/** Classes usable without escaping. */
const PLAIN = /^[A-Za-z_-][A-Za-z0-9_-]*$/;

/** A hash: five or more letters and digits, mixed (x1y2z3, a8f3k2). */
function isHash(name: string): boolean {
  return /^[a-z0-9]{5,}$/i.test(name) && /[a-z]\d+[a-z]/i.test(name);
}

/** Whether `name` looks generated by a build (and changes with it). */
export function isGeneratedClass(name: string): boolean {
  return (
    GENERATED_PREFIX.test(name) ||
    CSS_MODULE.test(name) ||
    isHash(name) ||
    (name.length >= 5 && name.length <= 8 && MIXED_CASE.test(name))
  );
}

/** Whether `id` looks generated (React `useId`, framework counters, UUIDs, hashes). */
export function isGeneratedId(id: string): boolean {
  return (
    id.includes(':') ||
    /^\d/.test(id) ||
    /\d{4,}/.test(id) ||
    /[0-9a-f]{8}-[0-9a-f]{4}/i.test(id) ||
    isHash(id)
  );
}

/** The document or open shadow root `element` lives in. */
export function rootOf(element: Element): Root {
  const root = element.getRootNode();
  return root instanceof ShadowRoot ? root : element.ownerDocument;
}

function stableClasses(element: Element): string[] {
  return Array.from(element.classList).filter(
    (name) => PLAIN.test(name) && !isGeneratedClass(name) && !STATE_CLASS.test(name),
  );
}

function step(node: Element): string {
  const tag = CSS.escape(node.localName);
  const parent = node.parentElement ?? (node.parentNode as ParentNode | null);
  if (!parent) return tag;
  const same = Array.from(parent.children).filter((child) => child.localName === node.localName);
  if (same.length === 1) return tag;
  for (const name of stableClasses(node)) {
    if (same.filter((child) => child.classList.contains(name)).length === 1) {
      return `${tag}.${CSS.escape(name)}`;
    }
  }
  return `${tag}:nth-of-type(${same.indexOf(node) + 1})`;
}

/** The CSS path of `element` in its root: up to the nearest stable unique id, else the top. */
export function cssPath(element: Element): string {
  const root = rootOf(element);
  const parts: string[] = [];
  for (let node: Element | null = element; node; node = node.parentElement) {
    if (node.id && !isGeneratedId(node.id)) {
      const byId = `#${CSS.escape(node.id)}`;
      if (root.querySelectorAll(byId).length === 1) {
        parts.unshift(byId);
        break;
      }
    }
    parts.unshift(step(node));
  }
  return parts.join(' > ');
}

/**
 * Where `selector` is looked for in `root`: inside its `within` element (RB-090-84) when `root`
 * has one, else `root` - a breakpoint without that container falls back to the whole page.
 */
function scopeOf(selector: ElementSelector, root: Root): ParentNode {
  const within = selector.kind === 'role' || selector.kind === 'text' ? selector.within : undefined;
  if (!within) return root;
  try {
    return root.querySelector(within) ?? root;
  } catch {
    return root;
  }
}

/** Every element `selector` matches in `root`, in document order (its `nth` not applied). */
export function matchAll(selector: ElementSelector, root: Root): Element[] {
  try {
    const scope = scopeOf(selector, root);
    switch (selector.kind) {
      case 'testid':
        return Array.from(root.querySelectorAll(`[data-testid="${CSS.escape(selector.testid)}"]`));
      case 'role': {
        const tags = ROLE_TAGS[selector.role];
        const query = `[role="${CSS.escape(selector.role)}"]${tags ? `,${tags}` : ''}`;
        return Array.from(scope.querySelectorAll(query)).filter((element) => {
          const role = roleOf(element);
          return role === selector.role && nameOf(element, role) === selector.name;
        });
      }
      case 'text':
        return Array.from(scope.querySelectorAll(CSS.escape(selector.tag))).filter(
          (element) => normalize(originalText(element)) === selector.text,
        );
      case 'css':
        return Array.from(root.querySelectorAll(selector.path));
    }
  } catch {
    // A path from a page with odd markup that this engine does not parse: nothing matches.
    return [];
  }
}

function withNth<T extends ElementSelector>(selector: T, nth: number): T {
  return nth > 0 ? { ...selector, nth } : selector;
}

/**
 * A role or text selector at `nth` of `matches`: with `visibleNth`, the element's index among
 * the visible ones, when it is a later match and shown itself (RB-090-81).
 */
function withVisibleNth<T extends ElementSelector>(
  selector: T,
  matches: Element[],
  element: Element,
): T {
  const nth = matches.indexOf(element);
  const numbered = withNth(selector, nth);
  if (nth === 0 || !isVisible(element)) return numbered;
  return { ...numbered, visibleNth: matches.filter(isVisible).indexOf(element) };
}

/** Landmarks that scope a selector by their tag when the page has one of them only. */
const LANDMARKS = ['header', 'nav', 'main', 'aside', 'footer'];

type Scoped = Extract<ElementSelector, { kind: 'role' | 'text' }>;

/**
 * The nearest ancestor of `element` - one with a stable unique id, or the page's only landmark
 * of its kind - inside which `selector` matches `element` alone, as a CSS selector; null when
 * none does.
 */
function uniqueScope(selector: Scoped, element: Element, root: Root): string | null {
  for (let node = element.parentElement; node; node = node.parentElement) {
    let css: string | null = null;
    if (node.id && !isGeneratedId(node.id)) css = `#${CSS.escape(node.id)}`;
    else if (LANDMARKS.includes(node.localName)) css = node.localName;
    if (css === null || root.querySelectorAll(css).length !== 1) continue;
    const inside = matchAll({ ...selector, within: css }, root);
    if (inside.length === 1 && inside[0] === element) return css;
  }
  return null;
}

/**
 * A role or text selector of `element` among `matches` (RB-090-84). Several shown at once - a
 * mega menu's link and a content link of the same name - is narrowed to the nearest ancestor
 * that makes it unique (`within`): a view that shows the content link first, before the menu
 * opens, still waits for the menu's. Without such an ancestor - and for a shown element with
 * hidden twins (a breakpoint's copy of the navigation) - it keeps its visible index
 * (RB-090-81): a CSS path differs between the breakpoints' DOMs, so the live sync would lose it.
 */
function narrowed(selector: Scoped, matches: Element[], element: Element, root: Root): Scoped {
  const ambiguous = isVisible(element) && matches.filter(isVisible).length > 1;
  const within = ambiguous ? uniqueScope(selector, element, root) : null;
  return within === null ? withVisibleNth(selector, matches, element) : { ...selector, within };
}

/** The selector of `element`, the strongest kind that finds it. */
export function makeSelector(element: Element): ElementSelector {
  const root = rootOf(element);
  const path = cssPath(element);
  const candidates: ElementSelector[] = [];
  const testid = element.getAttribute('data-testid');
  if (testid) candidates.push({ kind: 'testid', testid, path });
  const role = roleOf(element);
  const name = role ? nameOf(element, role) : '';
  if (role && name && name.length <= MAX_NAME) candidates.push({ kind: 'role', role, name, path });
  for (const candidate of candidates) {
    const matches = matchAll(candidate, root);
    if (!matches.includes(element)) continue;
    return candidate.kind === 'role'
      ? narrowed(candidate, matches, element, root)
      : withNth(candidate, matches.indexOf(element));
  }
  // A stable unique id says more than a text that may change with the content.
  if (path.startsWith('#') && !path.includes(' ')) return { kind: 'css', path };
  const text = normalize(originalText(element));
  const tag = element.localName;
  if (
    text &&
    text.length <= MAX_TEXT &&
    tag !== 'html' &&
    tag !== 'body' &&
    !element.querySelector(CONTROLS)
  ) {
    const candidate: Scoped = { kind: 'text', tag, text, path };
    const matches = matchAll(candidate, root);
    if (matches.includes(element)) return narrowed(candidate, matches, element, root);
  }
  return { kind: 'css', path };
}

/** A selector for people (desync tooltips, logs): `[data-testid="save"]`, `role=button[...]`. */
export function describeSelector(selector: ElementSelector): string {
  const nth = 'nth' in selector && selector.nth ? ` >> nth=${selector.nth}` : '';
  const within = 'within' in selector && selector.within ? `${selector.within} >> ` : '';
  switch (selector.kind) {
    case 'testid':
      return `[data-testid="${selector.testid}"]${nth}`;
    case 'role':
      return `${within}role=${selector.role}[name="${selector.name}"]${nth}`;
    case 'text':
      return `${within}${selector.tag}:text("${selector.text}")${nth}`;
    case 'css':
      return selector.path;
  }
}

/** What a pointer on `element` is meant for: its nearest interactive ancestor, else itself. */
export function actionable(element: Element): Element {
  return element.closest(ACTIONABLE) ?? element;
}

function clamp(value: number): number {
  const bounded = Math.min(1, Math.max(0, value));
  return Math.round(bounded * 10000) / 10000;
}

/** The open shadow hosts above `element`, from the document inward. */
function hostsOf(element: Element): Element[] {
  const hosts: Element[] = [];
  for (let root = element.getRootNode(); root instanceof ShadowRoot; ) {
    hosts.unshift(root.host);
    root = root.host.getRootNode();
  }
  return hosts;
}

/**
 * The target of a pointer at (`x`, `y`) (CSS pixels of the frame's viewport) on `element`:
 * its actionable ancestor, the shadow hosts above it and the relative offset in it.
 */
export function makeTarget(element: Element, x: number, y: number): ElementTarget {
  const subject = actionable(element);
  const rect = subject.getBoundingClientRect();
  const offset = {
    x: rect.width > 0 ? clamp((x - rect.left) / rect.width) : 0.5,
    y: rect.height > 0 ? clamp((y - rect.top) / rect.height) : 0.5,
  };
  const hosts = hostsOf(subject);
  const target: ElementTarget = { element: makeSelector(subject), offset };
  if (hosts.length > 0) target.hosts = hosts.map(makeSelector);
  return target;
}

/** The target of an element without a pointer (focus, input, a scroll container): its centre. */
export function centreTarget(element: Element): ElementTarget {
  const hosts = hostsOf(element);
  const target: ElementTarget = { element: makeSelector(element), offset: { x: 0.5, y: 0.5 } };
  if (hosts.length > 0) target.hosts = hosts.map(makeSelector);
  return target;
}
