"""The wiki's MCP tool reference, reference/mcp-tools.md, written from the tool definitions.

    python3 -I scripts/lib/mcp_reference.py <repo root> <wiki dir> [--check]

The data: schema/mcp-tools.v1.json (every tool of the MCP server with its description, the
schema of its arguments, its target, guard and area, and the pending tools; generated from
rb-mcp by a test), schema/commands.v1.json (which command each tool runs, and the commands
without a tool), the tools and commands of the bundled first-party plugins (plugins/*/manifest.toml
with their own locales, plugin_manifests.py) and the English texts (locales/en.json and the
wave's parts) for the command titles. The page lists an overview, then the tools area by area with
a parameter table each, then each plugin's tools (marked; a name a core tool has is the core's,
as rb-mcp routes it), the prompts with their arguments and the resources with their URIs (when the
tools file has them, RB-095-01), then the tools still to come and the commands no tool runs.

Exit 0 when written (or, with --check, current - or no wiki, or no page yet: nothing generated
to compare); 1 when --check finds the page stale; 2 when the data does not read or a job id is
left in the page (scripts/lib/wiki_text.py: a parenthesis of them is dropped; a coming tool's
job is the planning's and not shown).
"""

import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import plugin_manifests  # noqa: E402
import settings_schema  # noqa: E402
from settings_schema import DataError  # noqa: E402
from wiki_text import job_ids_left, public_text  # noqa: E402

PAGE = "reference/mcp-tools.md"
TOOLS = "schema/mcp-tools.v1.json"
COMMANDS = "schema/commands.v1.json"
GENERATOR = "scripts/mcp-reference.sh"
REGENERATE = "RB_UPDATE_SCHEMA=1 cargo nextest run -p rb-mcp mcp_tools_file"

# The areas in the page's order, with their headings; an area not named here follows by id.
AREAS = {
    "views": "Views and navigation",
    "page": "Page",
    "logs": "Console, network and errors",
    "layout": "Breakpoints, emulation and layout",
    "config": "Project config",
    "project": "Project and settings",
    "app": "App",
}

TARGETS = {
    "all": '`"all"` (default), a view id or a breakpoint id',
    "one": "one view: a view id or a breakpoint id shown once; the active view when absent",
}

HEADER = """# MCP tools

> Generated by `scripts/mcp-reference.sh` from rBrowser's tool definitions
> (`schema/mcp-tools.v1.json`), command registry (`schema/commands.v1.json`) and the bundled
> plugins' manifests (`plugins/*/manifest.toml`); do not edit by hand.

Every tool of rBrowser's MCP server, area by area: what it does, its parameters, the views it
acts on and the command it runs. How to connect an agent is on [MCP server](reference/mcp).

A tool that acts on views takes **`target`**: `"all"` for every view (the default), a view id
from `views_list`, or a breakpoint id for every view showing that breakpoint. A tool marked
*one view* acts on exactly one view, the active one when `target` is absent. A **guarded** tool
needs a setting a person switches on, or refuses keys only a person may change. A tool marked
*(plugin: ...)* comes from a bundled first-party plugin, is named `<mcp_prefix>_<tool>` and is
there while that plugin is enabled.
"""

# What rb-mcp adds to every plugin tool's schema (crates/rb-mcp/src/tools/plugins.rs).
PLUGIN_TARGET = {
    "description": ('"all" (default), a view id or a breakpoint id; the plugin gets "all" or '
                    "a view id"),
    "anyOf": [{"type": "string"}, {"type": "integer", "minimum": 0}],
}
EVALUATE_NOTE = ("Runs JavaScript its caller supplies: answers only while a person allows "
                 "evaluate.")

MAX_DEPTH = 16


def cell(text) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def deref(node, root: dict, depth: int = 0):
    """`node` with a `$ref` into `root` followed."""
    while isinstance(node, dict) and isinstance(node.get("$ref"), str) and depth < MAX_DEPTH:
        pointer = node["$ref"]
        if not pointer.startswith("#/"):
            return node
        target = root
        for part in pointer[2:].split("/"):
            target = target.get(part) if isinstance(target, dict) else None
        if target is None:
            raise DataError(f"{TOOLS}: unresolved reference {pointer}")
        node = target
        depth += 1
    return node


def type_of(node, root: dict, depth: int = 0) -> str:
    """A parameter's type in words: `string`, `integer or string`, `array of string`, ..."""
    node = deref(node, root, depth)
    if not isinstance(node, dict) or depth > MAX_DEPTH:
        return "any"
    if "enum" in node and isinstance(node["enum"], list):
        return " or ".join(f"`{json.dumps(value)}`" for value in node["enum"] if value is not None)
    if "const" in node:
        return f"`{json.dumps(node['const'])}`"
    for key in ("anyOf", "oneOf"):
        if isinstance(node.get(key), list):
            parts = []
            for part in node[key]:
                if deref(part, root, depth) == {"type": "null"}:
                    continue
                text = type_of(part, root, depth + 1)
                if text not in parts:
                    parts.append(text)
            return " or ".join(parts) or "null"
    kind = node.get("type")
    if isinstance(kind, list):
        kinds = [k for k in kind if k != "null"]
        if kinds == ["array"]:
            kind = "array"
        else:
            return " or ".join(kinds) or "null"
    if kind == "array":
        items = node.get("items")
        return f"array of {type_of(items, root, depth + 1)}" if items else "array"
    if isinstance(kind, str):
        return kind
    return "any"


def describe(node: dict) -> str:
    text = node.get("description", "") if isinstance(node, dict) else ""
    if isinstance(node, dict) and "default" in node and node["default"] is not None:
        text = f"{text} Default: `{json.dumps(node['default'])}`.".strip()
    return text or "-"


def read_tools(root: Path):
    data = settings_schema.load_json(root / TOOLS, root)
    if not isinstance(data, dict) or data.get("version") != 1:
        raise DataError(f"{TOOLS}: not version 1 of the tools file")
    tools, pending = data.get("tools"), data.get("pending")
    if not isinstance(tools, list) or not isinstance(pending, list):
        raise DataError(f"{TOOLS}: tools or pending missing")
    for tool in tools:
        if not isinstance(tool, dict) or not all(
            isinstance(tool.get(name), str) for name in ("name", "area", "description", "target")
        ):
            raise DataError(f"{TOOLS}: a tool without name, area, description or target")
        if tool["target"] not in ("all", "one", "none"):
            raise DataError(f"{TOOLS}: {tool['name']} has the unknown target {tool['target']}")
        if not isinstance(tool.get("inputSchema"), dict):
            raise DataError(f"{TOOLS}: {tool['name']} has no input schema")
    for entry in pending:
        if not isinstance(entry, dict) or not all(
            isinstance(entry.get(name), str) for name in ("tool", "job")
        ):
            raise DataError(f"{TOOLS}: a pending entry without tool or job")
    return tools, pending


def read_prompts_resources(root: Path):
    """The prompts, resources and resource templates of the tools file; empty when it has none."""
    data = settings_schema.load_json(root / TOOLS, root)
    prompts = data.get("prompts", [])
    resources = data.get("resources", []) + data.get("resourceTemplates", [])
    if not isinstance(prompts, list) or not all(
        isinstance(p, dict) and isinstance(p.get("name"), str)
        and isinstance(p.get("arguments", []), list) for p in prompts
    ):
        raise DataError(f"{TOOLS}: a prompt without name or with arguments that are no list")
    for prompt in prompts:
        if not all(isinstance(a, dict) and isinstance(a.get("name"), str)
                   for a in prompt.get("arguments", [])):
            raise DataError(f"{TOOLS}: {prompt['name']} has an argument without name")
    if not all(isinstance(r, dict) and isinstance(r.get("uri", r.get("uriTemplate")), str)
               for r in resources):
        raise DataError(f"{TOOLS}: a resource without uri")
    return prompts, resources


def prompts_resources(prompts: list, resources: list) -> list:
    """The page's sections of the prompts and the resources; none for a tools file without."""
    out = []
    if prompts:
        out.append("## Prompts\n")
        out.append("Ready texts for rBrowser's typical workflows, offered while the setting "
                   "`mcp.prompts` is on (`prompts/list`, `prompts/get`). A prompt runs nothing: "
                   "the agent calls the tools.\n")
        for prompt in prompts:
            out.append(f"### `{prompt['name']}`\n")
            out.append(cell(prompt.get("description") or "-") + "\n")
            arguments = prompt.get("arguments", [])
            if not arguments:
                out.extend(["No arguments.", ""])
                continue
            out.append("| Argument | Required | Description |")
            out.append("| --- | --- | --- |")
            for argument in arguments:
                needed = "yes" if argument.get("required") else "no"
                text = cell(argument.get("description") or "-")
                out.append(f"| `{cell(argument['name'])}` | {needed} | {text} |")
            out.append("")
    if resources:
        out.append("## Resources\n")
        out.append("rBrowser's state to read without a tool call, read-only, offered while the "
                   "setting `mcp.resources` is on (`resources/list`, `resources/read`).\n")
        out.append("| Resource | Type | Description |")
        out.append("| --- | --- | --- |")
        for resource in resources:
            uri = resource.get("uri", resource.get("uriTemplate"))
            kind = cell(resource.get("mimeType") or "-")
            out.append(f"| `{cell(uri)}` | {kind} | {cell(resource.get('description') or '-')} |")
        out.append("")
    return out


def read_commands(root: Path) -> list:
    data = settings_schema.load_json(root / COMMANDS, root)
    commands = data.get("commands") if isinstance(data, dict) else None
    if not isinstance(commands, list):
        raise DataError(f"{COMMANDS}: commands missing")
    for command in commands:
        mcp = command.get("mcp") if isinstance(command, dict) else None
        if not isinstance(command, dict) or not isinstance(command.get("id"), str):
            raise DataError(f"{COMMANDS}: a command without id")
        if not isinstance(mcp, dict) or not (
            isinstance(mcp.get("covered"), str) or isinstance(mcp.get("omitted"), str)
        ):
            raise DataError(f"{COMMANDS}: {command['id']} is neither covered nor omitted")
    return commands


def command_cell(command: dict, texts: dict) -> str:
    title = command.get("title") or texts.get(command.get("titleKey", ""), "")
    text = f"`{command['id']}` ({cell(title)})" if title else f"`{command['id']}`"
    return f"{text} {command['marker']}" if command.get("marker") else text


def plugin_data(root: Path, core: set) -> tuple[list, list, dict]:
    """The bundled plugins' tools (a core tool's name left out) and commands in the shape of the
    data files, and the headings of their areas."""
    tools, commands, headings = [], [], {}
    for plugin in plugin_manifests.bundled(root):
        area = f"plugin:{plugin.id}"
        mark = plugin_manifests.marker(plugin.name)
        for tool in plugin.tools:
            if tool.name in core:
                continue
            headings[area] = f"Plugin: {plugin.name}"
            schema = dict(tool.input_schema)
            schema["properties"] = {**(schema.get("properties") or {}), "target": PLUGIN_TARGET}
            entry = {"name": tool.name, "area": area, "target": "all",
                     "description": f"{tool.description} {mark}", "inputSchema": schema}
            if tool.evaluates_input:
                entry["guard"] = {"setting": plugin_manifests.EVALUATE_SETTING,
                                  "note": EVALUATE_NOTE}
            tools.append(entry)
        for command in plugin.commands:
            commands.append({"id": command.id, "title": command.title, "marker": mark,
                             "mcp": command.mcp})
    return tools, commands, headings


def target_text(tool: dict) -> str:
    if tool["target"] == "none":
        acts_on = tool.get("actsOn")
        return f"none - acts on {cell(acts_on)}" if acts_on else "none"
    return TARGETS[tool["target"]]


def parameters(tool: dict) -> list:
    schema = tool["inputSchema"]
    props = schema.get("properties") or {}
    if not props:
        return ["No parameters.", ""]
    required = set(schema.get("required") or [])
    out = ["| Parameter | Type | Required | Description |", "| --- | --- | --- | --- |"]
    for name, node in props.items():
        own = node if isinstance(node, dict) else {}
        kind = cell(type_of(own, schema))
        needed = "yes" if name in required else "no"
        out.append(f"| `{name}` | {kind} | {needed} | {cell(describe(own))} |")
    out.append("")
    return out


def render(root: Path) -> str:
    tools, pending = read_tools(root)
    commands = read_commands(root)
    texts = settings_schema.catalogue(root)
    extra_tools, extra_commands, headings = plugin_data(root, {t["name"] for t in tools})
    tools, commands = tools + extra_tools, commands + extra_commands
    names = {**AREAS, **headings}
    runs = {}
    for command in commands:
        if "covered" in command["mcp"]:
            runs.setdefault(command["mcp"]["covered"], []).append(command)
    areas = list(AREAS) + sorted({t["area"] for t in tools} - set(names)) + list(headings)
    by_area = {area: sorted((t for t in tools if t["area"] == area), key=lambda t: t["name"])
               for area in areas}
    out = [HEADER]
    out.append("| Tool | Area | Target | Command | Guarded |")
    out.append("| --- | --- | --- | --- | --- |")
    for area in areas:
        for tool in by_area[area]:
            name = tool["name"]
            ran = ", ".join(f"`{c['id']}`" for c in runs.get(name, [])) or "-"
            guarded = "yes" if tool.get("guard") else "-"
            target = {"all": "all", "one": "one view", "none": "-"}[tool["target"]]
            title = names.get(area, area)
            out.append(f"| [`{name}`](#{name}) | {cell(title)} | {target} | {ran} | {guarded} |")
    out.append("")
    for area in areas:
        if not by_area[area]:
            continue
        out.append(f"## {cell(names.get(area, area))}\n")
        for tool in by_area[area]:
            name = tool["name"]
            out.append(f"### `{name}`\n")
            out.append(cell(tool["description"]) + "\n")
            out.append(f"- **Target:** {target_text(tool)}")
            ran = runs.get(name, [])
            if ran:
                out.append("- **Command:** " + ", ".join(command_cell(c, texts) for c in ran))
            else:
                why = tool.get("withoutCommand")
                out.append(f"- **Command:** none - {cell(why)}" if why else "- **Command:** none")
            guard = tool.get("guard")
            if isinstance(guard, dict):
                setting = guard.get("setting")
                note = cell(guard.get("note", ""))
                lead = f"setting `{setting}`. " if setting and setting not in note else ""
                out.append(f"- **Guarded:** {lead}{note}")
            out.append("")
            out.extend(parameters(tool))
    out.extend(prompts_resources(*read_prompts_resources(root)))
    out.append("## Coming tools\n")
    out.append("Commands name these tools already; the tools themselves are still to come.\n")
    out.append("| Tool | Command |")
    out.append("| --- | --- |")
    for entry in sorted(pending, key=lambda e: e["tool"]):
        ran = ", ".join(f"`{c['id']}`" for c in runs.get(entry["tool"], [])) or "-"
        out.append(f"| `{cell(entry['tool'])}` | {ran} |")
    out.append("")
    out.append("## Commands without a tool\n")
    out.append("These commands are not reachable over MCP, each for the reason given.\n")
    out.append("| Command | Reason |")
    out.append("| --- | --- |")
    for command in sorted(commands, key=lambda c: c["id"]):
        if "omitted" in command["mcp"]:
            out.append(f"| {command_cell(command, texts)} | {cell(command['mcp']['omitted'])} |")
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str]) -> int:
    if len(argv) < 3 or any(arg != "--check" for arg in argv[3:]):
        print("usage: mcp_reference.py <repo root> <wiki dir> [--check]", file=sys.stderr)
        return 2
    root, wiki = Path(argv[1]).resolve(), Path(argv[2])
    check = "--check" in argv[3:]
    try:
        text = public_text(render(root))
    except DataError as error:
        print(f"!! the tool data does not read: {error}", file=sys.stderr)
        print(f"   ({TOOLS} is regenerated with {REGENERATE})", file=sys.stderr)
        return 2
    left = job_ids_left(text, PAGE)
    if left:
        print("!! a job id is left in the page; drop it from the description:", file=sys.stderr)
        for line in left:
            print(f"   {line}", file=sys.stderr)
        return 2
    page = wiki / PAGE
    if not wiki.is_dir():
        print(f"==> no wiki at {wiki}: the tool data reads, the page is not checked")
        return 0
    if check:
        if not page.is_file():
            print(f"==> {page} is not generated yet: run {GENERATOR}")
            return 0
        if page.read_text(encoding="utf-8") != text:
            print(f"!! {page} is stale: run {GENERATOR}")
            return 1
        print(f"==> {page} is current")
        return 0
    page.parent.mkdir(parents=True, exist_ok=True)
    page.write_text(text, encoding="utf-8")
    print(f"==> wrote {page}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
