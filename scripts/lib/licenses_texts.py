"""THIRD-PARTY-LICENSES.txt: the full licence texts of every package rBrowser ships (RB-099-12).

scripts/lib/licenses.py hands over the shipped packages (the rows of the About page's list with
the folder each one's files are in: a crate's source in the cargo registry, an npm package's
folder of node_modules, which must hold the lock's version). Each package's licence files -
LICENSE*, LICENCE*, COPYING*, NOTICE*, COPYRIGHT*, UNLICENSE*, the files of a LICENSES/ folder
and the `license-file` of a crate's manifest - are given as the package ships them, with their
copyright lines; a text several packages ship alike (whitespace aside) is given once and names
them all. A package that ships no licence file (or only empty ones) gets the standard text of
each licence its SPDX expression names, from ui/src/about/licenses/texts/<id>.txt (`{copyright}`
there becomes the package's authors), and says so; without a standard text the package is
reported missing and nothing is written.

The packaging scripts put the file beside NOTICE (scripts/package-windows.sh,
scripts/package-linux.sh, scripts/package-macos.sh).
"""

import json
import re
import textwrap
from pathlib import Path

TEXTS = "packaging/THIRD-PARTY-LICENSES.txt"
STANDARD = "ui/src/about/licenses/texts"
LICENCE_NAME = re.compile(r"^(licen[cs]e|copying|notice|copyright|unlicense)", re.IGNORECASE)
SPDX_ID = re.compile(r"[A-Za-z0-9][A-Za-z0-9.+\-]*")
OPERATORS = {"AND", "OR", "WITH"}
RULE = "-" * 79

HEADER = """\
Third-party software in rBrowser
================================

rBrowser - the application, its shell, the sync agent, the sidecar and the
bundled plugins - is built from the Rust crates and npm packages below, each
unchanged and under its own licence. Settings > About > Licences lists the same
packages; NOTICE names the components shipped as files of their own (CEF,
Chromium, Node.js and others).

Each package is listed with the licence it declares (an SPDX expression) and
the numbers of the texts below that come with it: its licence files, with their
copyright lines, as the package ships them. A text several packages ship alike
is given once. A package that ships no licence file is given the standard text
of each licence it names, and says so.

Generated by scripts/licenses.sh from Cargo.lock and the npm lock files - do
not edit.
"""


def licence_files(folder: Path, license_file: str | None) -> list[Path]:
    """The licence files of a package folder, sorted by name."""
    found: list[Path] = []
    for entry in sorted(folder.iterdir(), key=lambda path: path.name):
        if entry.is_file() and LICENCE_NAME.match(entry.name):
            found.append(entry)
        elif entry.is_dir() and entry.name.upper() in ("LICENSES", "LICENCES"):
            found.extend(sorted((path for path in entry.iterdir() if path.is_file()), key=lambda p: p.name))
    if license_file:
        # A `license-file` outside the crate is packed into its root under its own name.
        for candidate in (folder / license_file, folder / Path(license_file).name):
            if candidate.is_file() and candidate.resolve() not in {path.resolve() for path in found}:
                found.append(candidate)
                break
    return found


def standard_ids(expression: str) -> list[str]:
    """The licence ids of an SPDX expression, in order, each once."""
    ids = [token for token in SPDX_ID.findall(expression) if token not in OPERATORS]
    return list(dict.fromkeys(ids))


def tidy(text: str) -> str:
    """Line ends, trailing blanks and surrounding empty lines of a licence file."""
    lines = [line.rstrip() for line in text.replace("\r\n", "\n").replace("\r", "\n").lstrip("\ufeff").split("\n")]
    return "\n".join(lines).strip("\n")


def authors(package: dict) -> str:
    """Whom the standard text's copyright line names."""
    names = list(package.get("authors") or [])
    if not names and package["kind"] == "npm" and package.get("folder"):
        manifest = Path(package["folder"]) / "package.json"
        if manifest.is_file():
            author = json.loads(manifest.read_text(encoding="utf-8")).get("author")
            name = author.get("name") if isinstance(author, dict) else author
            if name:
                names = [name]
    return ", ".join(names) if names else f"the authors of {package['name']}"


def texts_of(package: dict, standard: Path, missing: list[str]) -> tuple[list[tuple[str, str]], bool]:
    """(label, text) of every licence text of `package`, and whether they are standard texts."""
    key = f"{package['name']}@{package['version']}"
    folder = Path(package["folder"]) if package.get("folder") else None
    if folder is None or not folder.is_dir():
        where = package.get("missing_hint") or f"no sources at {folder}"
        missing.append(f"{key}: {where}")
        return [], False
    if package["kind"] == "npm":
        # The folder must hold the lock's version: after a lock bump without `npm ci` it does not.
        manifest = folder / "package.json"
        installed = json.loads(manifest.read_text(encoding="utf-8")).get("version") if manifest.is_file() else None
        if installed != package["version"]:
            front_end = package.get("front_end", "the front end")
            if installed is None:
                missing.append(f"{key}: {package.get('missing_hint') or f'no package.json in {folder}'}")
            else:
                missing.append(f"{key}: {front_end}/node_modules has {installed} - run npm ci in {front_end}/")
            return [], False
    files = licence_files(folder, package.get("license_file"))
    texts = [(path.name, tidy(path.read_bytes().decode("utf-8", errors="replace"))) for path in files]
    texts = [(label, text) for label, text in texts if text]
    if texts:
        return texts, False
    # No licence file, or only empty ones: the standard texts.
    for licence in standard_ids(package["license"]):
        path = standard / f"{licence}.txt"
        if not path.is_file():
            missing.append(f"{key}: ships no licence file and {licence} has no standard text in {STANDARD}")
            continue
        text = path.read_text(encoding="utf-8").replace("{copyright}", f"Copyright (c) {authors(package)}")
        texts.append((f"The standard text of {licence}", tidy(text)))
    return texts, True


def render(packages: list[dict], standard: Path) -> tuple[str, list[str]]:
    """The file's text and what has no licence text. `packages`: dicts with kind (`rust` or
    `npm`), name, version, license, folder, and for crates license_file and authors."""
    missing: list[str] = []
    sections: dict[str, dict] = {}
    index: dict[str, list[str]] = {"rust": [], "npm": []}
    for package in packages:
        label_of = f"{package['name']} {package['version']}"
        texts, standard_texts = texts_of(package, standard, missing)
        numbers = []
        for label, text in texts:
            key = " ".join(text.split())
            if key not in sections:
                title = label if standard_texts else f"{label} of {label_of}"
                sections[key] = {"number": len(sections) + 1, "title": title, "text": text, "users": []}
            section = sections[key]
            if label_of not in section["users"]:
                section["users"].append(label_of)
            numbers.append(f"[{section['number']}]")
        note = " - ships no licence file; the standard text" if standard_texts else ""
        index[package["kind"]].append(f"  {label_of} ({package['license']}): {', '.join(numbers)}{note}")
    parts = [HEADER.rstrip("\n"), "", "", "Rust crates", "-----------", *index["rust"], "", "npm packages", "------------"]
    parts += [*index["npm"], "", "", "Licence texts", "============="]
    for section in sections.values():
        # No break inside a name and its version (U+00A0 is no break point for textwrap).
        users = ", ".join(user.replace(" ", "\u00a0") for user in section["users"])
        users = textwrap.fill(f"Used by: {users}", width=79, subsequent_indent="  ", break_on_hyphens=False)
        users = users.replace("\u00a0", " ")
        parts += ["", RULE, f"[{section['number']}] {section['title']}", users, RULE, "", section["text"]]
    return "\n".join(parts) + "\n", missing
