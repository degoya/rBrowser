"""The wiki's settings reference, reference/settings.md, written from the settings schemas.

    python3 -I scripts/lib/settings_reference.py <repo root> <wiki dir> [--check]

The data is the settings lint's (settings_schema.py): the categories and sections of
crates/rb-settings, the x-* annotations of the core schemas and the bundled plugins' fragments,
the English texts. The page lists the categories in the window's order, inside each its
sections, inside each its keys by x-order.

Exit 0 when written (or, with --check, current - or no wiki, or no page yet: nothing generated
to compare); 1 when --check finds the page stale; 2 when the data does not read or the lint
finds a problem (the page is never written from data the lint refuses).
"""

import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import settings_lint  # noqa: E402
import settings_schema  # noqa: E402
from settings_schema import DataError  # noqa: E402

PAGE = "reference/settings.md"

HEADER = """# Settings

> Generated by `scripts/settings-reference.sh` from rBrowser's settings schemas (`schema/`), the
> settings categories (`crates/rb-settings`), the bundled plugins' settings and the English texts;
> do not edit by hand.

Every setting of the settings window, category by category and section by section in the
window's order. The key is the name in the config files and the name the MCP tools
`settings_get` and `settings_set` use; `rbrowser://settings/<key>` opens the window at the key.

- **Scopes**: where a value may be stored - *User* (`%APPDATA%\\rBrowser\\settings.json`),
  *Project* (`.rbrowser/config.json`, checked in), *Local* (`.rbrowser/config.local.json`, this
  machine). Local wins over Project, Project over User, User over the default.
- **Local only**: valid only in `config.local.json`; in `config.json` it is ignored with a warning.
- **Protected**: only a person in the window changes it; MCP refuses it for every caller.
"""


def cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def values(schema: dict) -> str:
    """What a key takes, from its schema's type, enum and bounds."""
    if isinstance(schema.get("enum"), list):
        return ", ".join(f"`{json.dumps(item)}`" for item in schema["enum"])
    kind = schema.get("type")
    kinds = kind if isinstance(kind, list) else [kind] if kind else []
    words = {
        "boolean": "On or off", "integer": "A whole number", "number": "A number",
        "string": "Text", "array": "A list", "object": "An object", "null": "None",
    }
    text = " or ".join(words.get(k, str(k)) for k in kinds if k != "null") or "See the schema"
    low, high = schema.get("minimum"), schema.get("maximum")
    if low is not None and high is not None:
        text += f" from {low} to {high}"
    elif low is not None:
        text += f", at least {low}"
    elif high is not None:
        text += f", at most {high}"
    return text


def default(schema: dict) -> str:
    if "default" not in schema:
        return "-"
    return f"`{json.dumps(schema['default'], separators=(', ', ': '))}`"


def row(setting, texts: dict) -> str:
    label = texts.get(setting.label_key, setting.key)
    description = texts.get(setting.description_key, "")
    name = f"**{cell(label)}**" + (f" - {cell(description)}" if description else "")
    scopes = ", ".join(scope.capitalize() for scope in setting.scopes)
    notes = []
    if setting.local_only:
        notes.append("local only")
    if setting.protected:
        notes.append("protected")
    if setting.plugin:
        notes.append(f"plugin `{setting.plugin}`")
    link = f"`rbrowser://settings/{setting.key}`"
    return (
        f"| `{setting.key}` | {name} | {cell(values(setting.schema))} | "
        f"{cell(default(setting.schema))} | {scopes} | {', '.join(notes) or '-'} | {link} |"
    )


def render(root: Path) -> str:
    problems, _ = settings_lint.lint(root)
    if problems:
        raise DataError("the settings lint finds problems; run scripts/check-settings.sh")
    settings, _ = settings_schema.read_all(root)
    texts = settings_schema.catalogue(root)
    for plugin in settings_schema.plugins(root):
        texts = {**plugin.catalogue, **texts}
    out = [HEADER]
    for category, sections in settings_schema.categories(root):
        out.append(f"## {texts.get(f'settings.category.{category}', category)}\n")
        own = [s for s in settings if s.category == category]
        if not own:
            out.append("No settings yet.\n")
            continue
        for section in sections:
            rows = sorted(
                (s for s in own if s.section == section), key=lambda s: (s.order, s.key)
            )
            if not rows:
                continue
            out.append(f"### {texts.get(f'settings.section.{category}.{section}', section)}\n")
            out.append("| Key | Setting | Values | Default | Scopes | Notes | Deep link |")
            out.append("| --- | --- | --- | --- | --- | --- | --- |")
            out.extend(row(s, texts) for s in rows)
            out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str]) -> int:
    if len(argv) < 3 or any(arg != "--check" for arg in argv[3:]):
        print("usage: settings_reference.py <repo root> <wiki dir> [--check]", file=sys.stderr)
        return 2
    root, wiki = Path(argv[1]).resolve(), Path(argv[2])
    check = "--check" in argv[3:]
    try:
        text = render(root)
    except DataError as error:
        print(f"!! the settings data does not read: {error}", file=sys.stderr)
        return 2
    page = wiki / PAGE
    if not wiki.is_dir():
        print(f"==> no wiki at {wiki}: the settings data reads, the page is not checked")
        return 0
    if check:
        if not page.is_file():
            print(f"==> {page} is not generated yet: run scripts/settings-reference.sh")
            return 0
        if page.read_text(encoding="utf-8") != text:
            print(f"!! {page} is stale: run scripts/settings-reference.sh")
            return 1
        print(f"==> {page} is current")
        return 0
    page.parent.mkdir(parents=True, exist_ok=True)
    page.write_text(text, encoding="utf-8")
    print(f"==> wrote {page}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
