"""The wiki's keyboard reference, reference/keyboard-shortcuts.md, written from the registry.

    python3 -I scripts/lib/keyboard_reference.py <repo root> <wiki dir> [--check]

The data: schema/commands.v1.json (every command with its leader group, default bindings and MCP
mapping, generated from the command registry by a test of crates/rbrowser), the commands of the
bundled first-party plugins (plugins/*/manifest.toml with their own locales, plugin_manifests.py),
the reservation list crates/rb-commands/data/reserved-shortcuts.json and the English texts
(locales/en.json and the wave's parts). The page lists the groups in the leader's order, inside
each its commands by id (a plugin's marked), then the reserved combinations by where they come
from.

Exit 0 when written (or, with --check, current - or no wiki, or no page yet: nothing generated
to compare); 1 when --check finds the page stale; 2 when the data does not read.
"""

import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import plugin_manifests  # noqa: E402
import settings_schema  # noqa: E402
from settings_schema import DataError  # noqa: E402

PAGE = "reference/keyboard-shortcuts.md"
COMMANDS = "schema/commands.v1.json"
RESERVED = "crates/rb-commands/data/reserved-shortcuts.json"
# Where a context entry of the reservation list holds (`KeyContext` in rb-commands).
CONTEXTS = {"canvas-board": "with the focus on the canvas board"}
GENERATOR = "scripts/keyboard-reference.sh"
REGENERATE = "RB_UPDATE_SCHEMA=1 cargo nextest run -p rbrowser commands_file"

# The headings of the reservation list's sources, in the page's order.
SOURCES = {
    "browser": "Browser",
    "devtools": "DevTools",
    "text-editing": "Text editing",
    "os": "Windows",
    "accesskey": "Page access keys",
    "altgr": "AltGr keyboards",
}

HEADER = """# Keyboard shortcuts: every command

> Generated by `scripts/keyboard-reference.sh` from rBrowser's command registry
> (`schema/commands.v1.json`), the bundled plugins' manifests (`plugins/*/manifest.toml`), the
> reservation list (`crates/rb-commands/data/reserved-shortcuts.json`) and the English texts; do
> not edit by hand.

Every command of rBrowser with its default keys, group by group in the leader's order.
**`⌘` stands for the leader `{leader}`**:
press it, let go, then type the keys that follow. Every key can be changed under
**Settings › Keyboard Shortcuts**; the scheme is explained in
[Keyboard shortcuts](reference/shortcuts).

The **MCP** column names the MCP tool that runs the command, or why there is none. A command
marked *(plugin: ...)* comes from a bundled first-party plugin and is there while that plugin is
enabled.
"""

RESERVED_INTRO = """## Reserved combinations

rBrowser never binds these, and the shortcut editor refuses them with the reason given here (see
[Keys rBrowser never takes](reference/shortcuts#keys-rbrowser-never-takes)). `<letter>`,
`<digit>`, `<arrow>` and `<char>` stand for every key of their kind, `<any>` for any key.
"""


def cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def keys(binding: str, leader: str) -> str:
    """A binding as the wiki writes it: the leader as `⌘`."""
    if binding == leader or binding.startswith(leader + " "):
        binding = "⌘" + binding[len(leader):]
    return f"`{cell(binding)}`"


def mcp(coverage) -> str:
    if isinstance(coverage, dict) and isinstance(coverage.get("covered"), str):
        return f"`{cell(coverage['covered'])}`"
    if isinstance(coverage, dict) and isinstance(coverage.get("omitted"), str):
        return f"none ({cell(coverage['omitted'])})"
    raise DataError(f"{COMMANDS}: an MCP mapping is neither covered nor omitted: {coverage!r}")


def read_commands(root: Path):
    data = settings_schema.load_json(root / COMMANDS, root)
    if not isinstance(data, dict) or data.get("version") != 1:
        raise DataError(f"{COMMANDS}: not version 1 of the commands file")
    leader, groups, commands = data.get("leader"), data.get("groups"), data.get("commands")
    if not isinstance(leader, str) or not isinstance(groups, list) or not isinstance(commands, list):
        raise DataError(f"{COMMANDS}: leader, groups or commands missing")
    ids = set()
    for group in groups:
        if not isinstance(group, dict) or not all(
            isinstance(group.get(name), str) for name in ("id", "key", "titleKey")
        ):
            raise DataError(f"{COMMANDS}: a group without id, key or titleKey")
        ids.add(group["id"])
    for command in commands:
        if not isinstance(command, dict) or not all(
            isinstance(command.get(name), str) for name in ("id", "titleKey", "group")
        ):
            raise DataError(f"{COMMANDS}: a command without id, titleKey or group")
        if command["group"] not in ids:
            raise DataError(f"{COMMANDS}: {command['id']} is in the unknown group {command['group']}")
        bindings = command.get("defaultBindings")
        if not isinstance(bindings, list) or not all(isinstance(b, str) for b in bindings):
            raise DataError(f"{COMMANDS}: {command['id']} has no list of default bindings")
    return leader, groups, commands


def read_reserved(root: Path) -> list:
    data = settings_schema.load_json(root / RESERVED, root)
    entries = data.get("entries") if isinstance(data, dict) else None
    if not isinstance(entries, list) or not all(
        isinstance(entry, dict)
        and all(isinstance(entry.get(name), str) for name in ("combo", "source", "reason"))
        for entry in entries
    ):
        raise DataError(f"{RESERVED}: entries without combo, source or reason")
    return entries


def plugin_rows(root: Path, groups: list) -> list:
    """The bundled plugins' commands in the shape of the commands file, their texts resolved."""
    ids = {group["id"] for group in groups}
    rows = []
    for command in plugin_manifests.commands(root):
        if command.group not in ids:
            raise DataError(
                f"{command.id} (a plugin's command) is in the unknown group {command.group}"
            )
        rows.append({
            "id": command.id,
            "title": f"{command.title} {plugin_manifests.marker(command.plugin)}",
            "group": command.group,
            "defaultBindings": command.bindings,
            "mcp": command.mcp,
        })
    return rows


def render(root: Path) -> str:
    leader, groups, commands = read_commands(root)
    reserved = read_reserved(root)
    texts = settings_schema.catalogue(root)
    commands = commands + plugin_rows(root, groups)
    out = [HEADER.replace("{leader}", leader)]
    for group in groups:
        title = texts.get(group["titleKey"], group["id"])
        out.append(f"## {cell(title)} (`⌘ {group['key']}`)\n")
        rows = [c for c in commands if c["group"] == group["id"]]
        if not rows:
            out.append("No commands yet.\n")
            continue
        out.append("| Command | Id | Default keys | MCP |")
        out.append("| --- | --- | --- | --- |")
        for command in sorted(rows, key=lambda c: c["id"]):
            bound = ", ".join(keys(b, leader) for b in command["defaultBindings"]) or "-"
            name = command.get("title") or texts.get(command["titleKey"], command["id"])
            tool = mcp(command.get("mcp"))
            out.append(f"| {cell(name)} | `{command['id']}` | {bound} | {tool} |")
        out.append("")
    out.append(RESERVED_INTRO)
    order = list(SOURCES) + sorted({e["source"] for e in reserved} - set(SOURCES))
    for source in order:
        rows = [e for e in reserved if e["source"] == source]
        if not rows:
            continue
        out.append(f"### {SOURCES.get(source, source)}\n")
        out.append("| Combination | Reason |")
        out.append("| --- | --- |")
        for entry in rows:
            reason = texts.get(entry.get("reasonKey", ""), entry["reason"])
            # A context entry (RB-080-94): the one place rBrowser takes the combination.
            exception = entry.get("except")
            if isinstance(exception, dict) and isinstance(exception.get("command"), str):
                where = CONTEXTS.get(exception.get("context"), exception.get("context"))
                reason += f"; {where} it runs `{exception['command']}`"
            out.append(f"| `{cell(entry['combo'])}` | {cell(reason)} |")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str]) -> int:
    if len(argv) < 3 or any(arg != "--check" for arg in argv[3:]):
        print("usage: keyboard_reference.py <repo root> <wiki dir> [--check]", file=sys.stderr)
        return 2
    root, wiki = Path(argv[1]).resolve(), Path(argv[2])
    check = "--check" in argv[3:]
    try:
        text = render(root)
    except DataError as error:
        print(f"!! the command data does not read: {error}", file=sys.stderr)
        print(f"   ({COMMANDS} is regenerated with {REGENERATE})", file=sys.stderr)
        return 2
    page = wiki / PAGE
    if not wiki.is_dir():
        print(f"==> no wiki at {wiki}: the command data reads, the page is not checked")
        return 0
    if check:
        if not page.is_file():
            print(f"==> {page} is not generated yet: run {GENERATOR}")
            return 0
        if page.read_text(encoding="utf-8") != text:
            print(f"!! {page} is stale: run {GENERATOR}")
            return 1
        print(f"==> {page} is current")
        return 0
    page.parent.mkdir(parents=True, exist_ok=True)
    page.write_text(text, encoding="utf-8")
    print(f"==> wrote {page}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
