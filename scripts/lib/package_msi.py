"""Writes files.wxs, the program files of rBrowser's MSI (RB-099-01), from an unpacked package.

    python3 -I scripts/lib/package_msi.py <unpacked package folder> <files.wxs>

A WiX 5 fragment: the package's folders as Directory elements below INSTALLFOLDER and the
component group `Program`, one component per folder with that folder's files. A per-user
component needs a key path under HKCU (ICE38) and a RemoveFolder for the folder it creates
(ICE64), so each has a registry value of its own and removes its folder on uninstall. Ids and
GUIDs are derived from the folder's and the file's path, so the same package writes the same
fragment and a component keeps its GUID from one release to the next. Called by
scripts/package-msi.sh, tested by scripts/tests/windows-paket-msi.sh.
"""

import hashlib
import os
import sys
import uuid
from xml.sax.saxutils import quoteattr

# The namespace of the component GUIDs; never changed, or every component gets a new one.
NAMESPACE = uuid.UUID("6b7f6c1e-4f0a-4d55-9a3e-2f1c8e0b5d71")
REGISTRY_KEY = r"Software\rBrowser\Installer"


def ident(prefix: str, relative: str) -> str:
    """An id WiX takes (a letter first, at most 72 characters) for the path `relative`."""
    return prefix + hashlib.sha256(relative.encode("utf-8")).hexdigest()[:32]


def source(relative: str) -> str:
    """The file's path below $(var.Stage); a `$` is doubled for the WiX preprocessor."""
    return "$(var.Stage)\\" + relative.replace("$", "$$")


def main() -> int:
    stage, target = sys.argv[1], sys.argv[2]
    folders: list[tuple[str, list[str], list[str]]] = []
    for folder, dirs, files in os.walk(stage):
        dirs.sort()
        relative = os.path.relpath(folder, stage)
        relative = "" if relative == "." else relative.replace(os.sep, "\\")
        folders.append((relative, list(dirs), sorted(files)))
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by scripts/package-msi.sh (scripts/lib/package_msi.py) from the unpacked",
        "     package: every file of it, one component per folder. Never edited by hand. -->",
        '<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">',
        "  <Fragment>",
        '    <DirectoryRef Id="INSTALLFOLDER">',
    ]

    children = {relative: dirs for relative, dirs, _ in folders}

    def tree(relative: str, depth: int) -> None:
        for child in children[relative]:
            path = f"{relative}\\{child}" if relative else child
            pad = "  " * depth
            lines.append(f"{pad}<Directory Id={quoteattr(ident('d', path))} Name={quoteattr(child)}>")
            tree(path, depth + 1)
            lines.append(f"{pad}</Directory>")

    tree("", 3)
    lines += ["    </DirectoryRef>", '    <ComponentGroup Id="Program">']
    for relative, _, files in folders:
        directory = ident("d", relative) if relative else "INSTALLFOLDER"
        guid = str(uuid.uuid5(NAMESPACE, "folder:" + relative)).upper()
        lines.append(
            f"      <Component Id={quoteattr(ident('c', relative))} Directory={quoteattr(directory)}"
            f" Guid={quoteattr(guid)}>"
        )
        lines.append(
            f"        <RegistryValue Root=\"HKCU\" Key={quoteattr(REGISTRY_KEY)}"
            f" Name={quoteattr('folder:' + (relative or '.'))} Type=\"integer\" Value=\"1\" KeyPath=\"yes\" />"
        )
        for name in files:
            path = f"{relative}\\{name}" if relative else name
            lines.append(
                f"        <File Id={quoteattr(ident('f', path))} Name={quoteattr(name)}"
                f" Source={quoteattr(source(path))} />"
            )
        lines.append(f"        <RemoveFolder Id={quoteattr(ident('r', relative))} On=\"uninstall\" />")
        lines.append("      </Component>")
    lines += ["    </ComponentGroup>", "  </Fragment>", "</Wix>", ""]
    with open(target, "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
