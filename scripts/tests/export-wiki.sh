#!/usr/bin/env bash
#
# scripts/export-wiki.sh against a wiki in a temp directory: it writes
# reference/configuration.md from the checked-in schemas, a second run changes nothing, --check
# passes on a fresh page and fails on a stale or missing one, --dry-run writes nothing, a
# missing wiki is skipped by --check and refused by a write, and a broken schema is exit 2.
#
# Pure bash and python: it runs at once. check.sh --preflight runs it.
#
#   scripts/tests/export-wiki.sh
# shellcheck disable=SC2016  # the conditions are single-quoted on purpose: expect_true evaluates them
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SCRATCH="$(mktemp -d)"
trap 'rm -rf "$SCRATCH"' EXIT
WIKI="$SCRATCH/wiki"
PAGE="$WIKI/reference/configuration.md"
mkdir -p "$WIKI"

# shellcheck source=lib/expect.sh
source "$ROOT/scripts/tests/lib/expect.sh"

export RB_WIKI="$WIKI"
run_status "$ROOT/scripts/export-wiki.sh"
expect_status "a write succeeds" 0
expect_true "the page is written" '[[ -f "$PAGE" ]]'
expect_true "it says it is generated" 'head -1 "$PAGE" | grep -qF "Generated by scripts/export-wiki.sh"'
expect_true "it lists a nested key with its settings place" \
    'grep -qF "| \`sync.scroll\` | boolean | \`true\` | Sync › Scroll |" "$PAGE"'
expect_true "it marks a local-only key" \
    'grep -F "\`network.ignoreCertificateErrors\`" "$PAGE" | grep -qF "(local only)"'
expect_true "it marks a protected key" \
    'grep -F "\`mcp.allowEvaluate\`" "$PAGE" | grep -qF "(protected from MCP)"'
expect_true "it lists list entries and required fields" \
    'grep -qF "| \`breakpoints[].id\` | string, required |" "$PAGE"'
expect_true "the example comes from the fixture" 'grep -qF "\"desktop-ff\"" "$PAGE"'

before="$(cat "$PAGE")"
run_status "$ROOT/scripts/export-wiki.sh"
expect "a second write changes nothing" "$before" "$(cat "$PAGE")"
expect_output "and says so" "up to date"

run_status "$ROOT/scripts/export-wiki.sh" --check
expect_status "--check passes on a fresh page" 0

echo "edited by hand" >> "$PAGE"
run_status "$ROOT/scripts/export-wiki.sh" --check
expect_status "--check fails on a stale page" 1
expect_output "naming it" "reference/configuration.md: stale"

run_status "$ROOT/scripts/export-wiki.sh" --dry-run
expect_status "--dry-run succeeds" 0
expect_output "--dry-run names the page" "(would write)"
expect_true "--dry-run writes nothing" 'tail -1 "$PAGE" | grep -qF "edited by hand"'

rm "$PAGE"
run_status "$ROOT/scripts/export-wiki.sh" --check
expect_status "--check fails on a missing page" 1

RB_WIKI="$SCRATCH/none" run_status "$ROOT/scripts/export-wiki.sh" --check
expect_status "--check without a wiki skips the pages" 0
RB_WIKI="$SCRATCH/none" run_status "$ROOT/scripts/export-wiki.sh"
expect_status "a write without a wiki is refused" 2

FAKE="$SCRATCH/root"
mkdir -p "$FAKE/schema" "$FAKE/crates/rb-config/tests/fixtures/project/.rbrowser"
cp "$ROOT/schema/settings.v1.json" "$FAKE/schema/"
cp "$ROOT/crates/rb-config/tests/fixtures/project/.rbrowser/config.json" \
    "$FAKE/crates/rb-config/tests/fixtures/project/.rbrowser/"
echo "{" > "$FAKE/schema/config.v1.json"
run_status python3 -I "$ROOT/scripts/lib/export_wiki.py" "$FAKE" "$WIKI"
expect_status "a broken schema is exit 2" 2
expect_output "naming the file" "config.v1.json"

run_status "$ROOT/scripts/export-wiki.sh" --bogus
expect_status "an unknown option is exit 2" 2

finish_tests export-wiki
